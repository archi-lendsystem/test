  public static function getRate(int $age, int $tenure): ?float
{
    return self::$rateTable[$age][$tenure] ?? null;
}

  
  public static function calculatePremium(float $loanAmount, int $tenure, int $age): array
    {

    if ($age < 18 || $age > 65) {
        return ['error' => "Age {$age} is outside the supported range (18–65)."];
    }

    $rate = self::getRate($age, $tenure);

    if ($rate === null) {
        $validTenures = implode(', ', array_keys(self::$rateTable[$age] ?? []));
        return ['error' => "No rate found for age {$age} at tenure {$tenure} months. Supported tenures: {$validTenures}."];
    }

        
    
 
        $multiplier           = $loanAmount / 1000;                     
        $premiumBeforeGst     = round($rate * $multiplier);               
        $gst                  = round($premiumBeforeGst * 0.18);          
        $premiumAfterGst      = round($premiumBeforeGst + $gst);         
 
        return [
            'loan_amount'               => $loanAmount,
            'tenure'                    => $tenure,
            'age'                       => $age,
            'rate'                      => $rate,
            'multiplier'                => round($multiplier, 4),         
            'premium_amount_before_gst' => $premiumBeforeGst,
            'gst_amount'                => $gst,
            'premium_amount_after_gst'  => $premiumAfterGst,
        ];
    }
