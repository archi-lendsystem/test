<?php

declare(strict_types=1);

namespace Modules\BLReports\Services;

use Illuminate\Support\Facades\Storage;
use Modules\BLApplicantDetails\Models\BLApplicantDetails;
use Modules\BLLeadCreation\Models\BLLeadCreation;
use Modules\BLReports\Enums\BLReportStatus;
use Modules\BLReports\Exceptions\BLReportException;
use Modules\BLReports\Models\BLReport;
use Modules\ESign\Services\ESignService;

final class BLReportESignService
{
    public function __construct(
        private readonly ESignService $eSignService
    ) {
    }

    public function initiate(
        string $leadUuid,
        string $reportUuid,
        ?int $initiatedBy = null
    ): array {
        /*
         * Resolve the exact report belonging to this lead.
         */
        $report = BLReport::query()
            ->where('uuid', $reportUuid)
            ->where('lead_uuid', $leadUuid)
            ->first();

        if (! $report) {
            throw new BLReportException(
                message: 'Report not found.',
                statusCode: 404,
                errorCode: 'REPORT_NOT_FOUND'
            );
        }

        /*
         * eSign can only start for an already generated report.
         *
         * IMPORTANT:
         * We DO NOT change BLReport.status for eSign.
         */
        if (
            $report->status !== BLReportStatus::GENERATED
            || empty($report->file_path)
        ) {
            throw new BLReportException(
                message: 'Report is not ready for eSign.',
                statusCode: 409,
                errorCode: 'REPORT_NOT_READY_FOR_ESIGN'
            );
        }

        /*
         * Read the exact PDF already generated by BL Reports.
         *
         * Do NOT regenerate the document here.
         */
        $diskName = trim(
            (string) (
                $report->storage_disk
                ?: 'private'
            )
        );

        if ($diskName === '') {
            $diskName = 'private';
        }

        $disk = Storage::disk($diskName);

        if (! $disk->exists($report->file_path)) {
            throw new BLReportException(
                message: 'Report file not found.',
                statusCode: 404,
                errorCode: 'REPORT_FILE_NOT_FOUND'
            );
        }

        $pdfContent = $disk->get(
            $report->file_path
        );

        if (
            $pdfContent === ''
            || ! str_starts_with(
                $pdfContent,
                '%PDF'
            )
        ) {
            throw new BLReportException(
                message: 'Stored report is not a valid PDF.',
                statusCode: 409,
                errorCode: 'INVALID_REPORT_PDF'
            );
        }

        /*
         * Verify that the bytes being sent to Digio are
         * exactly the generated report bytes recorded in DB.
         */
        $actualChecksum = hash(
            'sha256',
            $pdfContent
        );

        $expectedChecksum = trim(
            (string) $report->checksum
        );

        if (
            $expectedChecksum === ''
            || ! hash_equals(
                strtolower($expectedChecksum),
                strtolower($actualChecksum)
            )
        ) {
            throw new BLReportException(
                message: 'Report checksum verification failed.',
                statusCode: 409,
                errorCode: 'REPORT_CHECKSUM_MISMATCH'
            );
        }

        /*
         * Signer identity comes from existing business sources:
         *
         * - applicant name: primary BLApplicantDetails row
         * - email/mobile: BLLeadCreation
         *
         * This keeps Sanction and BL Report eSign consistent.
         */
        $lead = BLLeadCreation::query()
            ->where('uuid', $leadUuid)
            ->first();

        if (! $lead) {
            throw new BLReportException(
                message: 'Loan application not found.',
                statusCode: 404,
                errorCode: 'LEAD_NOT_FOUND'
            );
        }

        $applicantDetails =
            BLApplicantDetails::query()
                ->where('lead_uuid', $leadUuid)
                ->where('applicant_sno', 0)
                ->first();

        if (! $applicantDetails) {
            throw new BLReportException(
                message: 'Primary applicant details not found.',
                statusCode: 422,
                errorCode: 'PRIMARY_APPLICANT_NOT_FOUND'
            );
        }

        $email = trim(
            (string) (
                $lead->email
                ?? ''
            )
        );

        $mobile = trim(
            (string) (
                $lead->mobile_number
                ?? ''
            )
        );

        $contact = $email !== ''
            ? $email
            : $mobile;

        if ($contact === '') {
            throw new BLReportException(
                message: 'Applicant email or mobile number is required for eSign.',
                statusCode: 422,
                errorCode: 'ESIGN_CONTACT_REQUIRED'
            );
        }

        $signerName = trim(
            (string) (
                $applicantDetails->full_name
                ?? ''
            )
        );

        if ($signerName === '') {
            $signerName = 'Applicant';
        }

        /*
         * Keep document type deterministic and independent
         * from display labels.
         *
         * Examples:
         * LOAN_APPLICATION    -> loan_application
         * LOAN_AGREEMENT      -> loan_agreement
         * DPN                 -> dpn
         * KEY_FACT_STATEMENT  -> key_fact_statement
         * DECLARATION         -> declaration
         */
        $documentType = strtolower(
            $report->report_type->value
        );

        $fileName = basename(
            $report->file_path
        );

        if ($fileName === '') {
            $fileName =
                $report->report_type->filePrefix()
                . '.pdf';
        }

        $signers = [
            [
                'identifier' => $contact,
                'name' => $signerName,
                'sign_type' => 'aadhaar',
                'reason' =>
                    $report->document_name
                    . ' Signing',
            ],
        ];

        /*
         * module_id points to the exact BLReport row.
         *
         * module_type is separate from Sanction so there is
         * no ambiguity between Sanction and BL Report sources.
         */
        return $this->eSignService->initiateSigning([
            'lead_uuid' => $leadUuid,
            'module_type' => 'bl_reports',
            'module_id' => $report->id,
            'document_type' => $documentType,
            'file_name' => $fileName,
            'file_data' => base64_encode(
                $pdfContent
            ),
            'signers' => $signers,
            'initiated_by' => $initiatedBy,
        ]);
    }
}